/** "qr-code", "calendar_days" ou "QrCode" → componente; desconhecido → `fallback`. */
export function studentAppIcon(name: string, fallback: LucideIcon = Circle): LucideIcon {
  const key = name
    .split(/[-_ ]+/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join("");
  return STUDENT_APP_ICONS[key] ?? fallback;
}
